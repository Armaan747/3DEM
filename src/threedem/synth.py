"""Generate simple slicer-style G-code without a slicer.

Used by the tests and by ``threedem demo``.  The output mimics OrcaSlicer's
conventions (relative extrusion, ``;TYPE:``/``;WIDTH:``/``;HEIGHT:`` comments and
a trailing ``; key = value`` config block) so it exercises the same parser path.
"""

from __future__ import annotations

import math

_ROUND = 1 - math.pi / 4


def bar_gcode(
    length: float = 40.0,
    width: float = 8.0,
    height: float = 8.0,
    pitch: float = 0.4,
    layer_height: float = 0.2,
    pattern: str = "x",
    origin: tuple[float, float] = (0.0, 0.0),
    filament_diameter: float = 1.75,
) -> tuple[str, dict]:
    """G-code of a solid rectangular bar, fully dense.

    ``pattern`` is ``"x"`` (all lines along X), ``"y"`` (along Y) or ``"alt"``
    (alternating X and Y layers, like rectilinear infill at 0/90 degrees).
    Returns ``(gcode, dims)`` where ``dims`` gives the exact printed size, rounded
    to whole road pitches and layers.
    """
    road_w = pitch + layer_height * _ROUND  # a road overlaps its neighbours by the rounded edges
    area = layer_height * pitch  # so each pitch cell is exactly full
    fil_area = math.pi / 4 * filament_diameter**2
    nx = max(1, round(length / pitch))
    ny = max(1, round(width / pitch))
    nl = max(1, round(height / layer_height))
    x0, y0 = origin
    dims = {
        "length": nx * pitch, "width": ny * pitch, "height": nl * layer_height,
        "x0": x0, "y0": y0, "pitch": pitch, "layers": nl,
    }
    out = [
        "; synthetic G-code generated by threedem",
        "G90", "M83", "G92 E0",
    ]
    for layer in range(nl):
        z = (layer + 1) * layer_height
        along_x = pattern == "x" or (pattern == "alt" and layer % 2 == 0)
        out += [f";LAYER_CHANGE", f";Z:{z:.3f}", f";HEIGHT:{layer_height}", f"G1 Z{z:.3f} F1200", ";TYPE:Sparse infill", f";WIDTH:{road_w:.4f}"]
        if along_x:
            for j in range(ny):
                y = y0 + (j + 0.5) * pitch
                xa, xb = (x0, x0 + dims["length"]) if j % 2 == 0 else (x0 + dims["length"], x0)
                e = area * dims["length"] / fil_area
                out += [f"G0 X{xa:.4f} Y{y:.4f}", f"G1 X{xb:.4f} Y{y:.4f} E{e:.5f} F3000"]
        else:
            for i in range(nx):
                x = x0 + (i + 0.5) * pitch
                ya, yb = (y0, y0 + dims["width"]) if i % 2 == 0 else (y0 + dims["width"], y0)
                e = area * dims["width"] / fil_area
                out += [f"G0 X{x:.4f} Y{ya:.4f}", f"G1 X{x:.4f} Y{yb:.4f} E{e:.5f} F3000"]
    out += [
        "; CONFIG_BLOCK_START",
        f"; filament_diameter = {filament_diameter}",
        f"; layer_height = {layer_height}",
        "; nozzle_diameter = 0.4",
        "; CONFIG_BLOCK_END",
    ]
    return "\n".join(out) + "\n", dims
